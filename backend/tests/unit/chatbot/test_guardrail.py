@pytest.mark.parametrize(("expected", "phrases"), RISK_CASES)
def test_regex_guardrail_catches_at_least_eight_variants(expected: str, phrases: list[str]) -> None:
    assert len(phrases) >= 8
    for phrase in phrases:
        assert detect_risk_label(phrase) == expected, phrase


@pytest.mark.parametrize("phrase", NORMAL_QUESTIONS)
def test_normal_legal_questions_do_not_match_regex_guardrail(phrase: str) -> None:
    assert detect_risk_label(phrase) is None


def test_unqualified_transfer_is_not_complex_transfer_risk() -> None:
    assert detect_risk_label("Chuyển nhượng doanh nghiệp là gì?") is None


