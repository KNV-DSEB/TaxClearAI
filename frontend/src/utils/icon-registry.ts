function toKebabCase(pascalName: string): string {
  return pascalName
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/([A-Za-z])([0-9])/g, '$1-$2')
    .toLowerCase();
}

// kebab-case key -> component, e.g. 'bar-chart-3' -> BarChart3. Matches the
// naming already stored in apps.icon_key / app_categories.icon_key.
export const ICON_REGISTRY: Record<string, LucideIcon> = Object.fromEntries(
  Object.entries(ICON_COMPONENTS).map(([pascalName, component]) => [toKebabCase(pascalName), component])
);

export const ICON_KEYS = Object.keys(ICON_REGISTRY);

export const DEFAULT_ICON_NAME = 'boxes';

export function getIcon(iconKey: string | null | undefined): LucideIcon {
  return (iconKey && ICON_REGISTRY[iconKey]) || ICON_REGISTRY[DEFAULT_ICON_NAME];
}

